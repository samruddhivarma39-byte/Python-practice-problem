a = int(input("Enter first no: ")) 
b = int(input("Enter a second no:")) 
print("Addition: ", a+b) 
print("Subtraction: ",a-b) 
print("Multiplication: ",a*b) 
if b!=0:  
    print("Division: ",a/b)
    print("Modulus: ",a%b) 
    print("Floor Division: ",a//b) 
else: 
    print("Division is not possible")